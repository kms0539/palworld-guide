export function translateObtained(source, palNameLookup) {
  if (!source) return "";
  let text = String(source).trim();

  // Pattern: Dropped by [Name] x[Range] ([Prob]%)
  const dropMatch = text.match(/^Dropped by\s+(.+?)\s+x([\d~–-]+)\s*\(([\d.]+%)\)$/i);
  if (dropMatch) {
    const rawName = dropMatch[1].trim();
    const count = dropMatch[2];
    const prob = dropMatch[3];
    const name = npcTranslations[rawName] || (palNameLookup ? palNameLookup(rawName) : rawName);
    return `${name} 드롭 ×${count} (${prob})`;
  }

  // Pattern: Dropped by [Name]
  const dropSimple = text.match(/^Dropped by\s+(.+)$/i);
  if (dropSimple) {
    const rawName = dropSimple[1].trim();
    const name = npcTranslations[rawName] || (palNameLookup ? palNameLookup(rawName) : rawName);
    return `${name} 드롭`;
  }

  // Pattern: Sold by [Name] for [Price] Gold
  const soldMatch = text.match(/^Sold by\s+(.+?)\s+for\s+([\d,]+)\s+Gold$/i);
  if (soldMatch) {
    const rawName = soldMatch[1].trim();
    const price = soldMatch[2];
    const name = npcTranslations[rawName] || (palNameLookup ? palNameLookup(rawName) : rawName);
    return `${name} 판매 (${price} 골드)`;
  }

  // Pattern: Ranch: [Pal]
  const ranchMatch = text.match(/^Ranch:\s*(.+)$/i);
  if (ranchMatch) {
    const name = palNameLookup ? palNameLookup(ranchMatch[1].trim()) : ranchMatch[1].trim();
    return `목장 생산: ${name}`;
  }

  // Region / Dungeon / Treasure patterns
  text = text
    .replace(/Treasure_Grass_Grade_\d+:/gi, "초원 보물 상자:")
    .replace(/Grass\d+_Fishing:/gi, "초원 낚시:")
    .replace(/Forest\d+_Fishing:/gi, "산림 낚시:")
    .replace(/Desert\d+_Fishing:/gi, "사막 낚시:")
    .replace(/Volcano\d+_Fishing:/gi, "화산 낚시:")
    .replace(/Snow\d+_Fishing:/gi, "설산 낚시:")
    .replace(/WorldTree_Treasure_Fishing:/gi, "세계수 낚시:")
    .replace(/WorldTree_Treasure_Fishpond:/gi, "세계수 낚시터:")
    .replace(/WorldTree_Treasure:/gi, "세계수 보물 상자:")
    .replace(/Junk_WorldTree:/gi, "세계수 필드 채집:")
    .replace(/Sakurajima_Treasure_Fishing:/gi, "사쿠라지마 낚시:")
    .replace(/Sakurajima_Treasure_FishPond:/gi, "사쿠라지마 낚시터:")
    .replace(/Sakurajima_Treasure:/gi, "사쿠라지마 보물 상자:")
    .replace(/Feybreak_Treasure_Fishing:/gi, "페이브레이크 낚시:")
    .replace(/Feybreak_Treasure_FishPond:/gi, "페이브레이크 낚시터:")
    .replace(/Feybreak_Treasure:/gi, "페이브레이크 보물 상자:")
    .replace(/SkyIsland_Treasure_Fishing:/gi, "선리치 낚시:")
    .replace(/SkyIsland_Treasure_Fishpond:/gi, "선리치 낚시터:")
    .replace(/SkyIsland_Treasure:/gi, "선리치 보물 상자:")
    .replace(/Grass\d+_FishPond:/gi, "초원 낚시터:")
    .replace(/Forest\d+_FishPond:/gi, "산림 낚시터:")
    .replace(/Desert\d+_FishPond:/gi, "사막 낚시터:")
    .replace(/Volcano\d+_FishPond:/gi, "화산 낚시터:")
    .replace(/Snow\d+_FishPond:/gi, "설산 낚시터:")
    .replace(/EnemyCamp_(\w+):/gi, "적 캠프:")
    .replace(/Junk_(\w+):/gi, "필드 채집:")
    .replace(/Mining/gi, "채광")
    .replace(/Chest/gi, "상자")
    .replace(/Dungeon/gi, "던전")
    .replace(/TechnologyBook/gi, "기술서")
    .replace(/Elixir/gi, "영약");

  return text;
}

